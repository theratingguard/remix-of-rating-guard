const reviewerSignal = (
  _input: RuleReviewContext,
  id: string,
  value: boolean | null,
  evidence: string,
) => observed(id, "reviewer", value, 0, evidence);

export function evaluateAdditionalRules(input: RuleReviewContext): RuleCheck[] {
  const text = input.text;
  const words = text.match(/[\p{L}\p{N}]+/gu) ?? [];
  const wordCount = words.length;
  const reviewer = input.reviewer;
  const total = reviewer?.totalReviewCount;
  const oneStar = reviewer?.oneStarReviewCount;
  const oneStarShare =
    total !== undefined && total !== null && oneStar !== undefined && oneStar !== null && total > 0
      ? oneStar / total
      : null;
  const hour = reviewer?.reviewsInLastHour;
  const reviewedBusinesses = reviewer?.reviewedBusinessCount;
  const name = reviewer?.name;
  const age = reviewer?.accountAgeDays;
  const nameLength = name?.trim().length;
  const time = input.reviewDate ? new Date(input.reviewDate) : null;
  const validTime = time !== null && Number.isFinite(time.getTime());

  const measuredText = textForensicsPatterns.map(([id, pattern]) =>
    observed(
      id,
      "text",
      wordCount ? pattern.test(text) : null,
      0,
      "Deterministic text-format observation only; formatting is not evidence of a policy violation.",
    ),
  );
  const measuredReviewer = [
    reviewerSignal(
      input,
      ids.reviewer[0],
      age == null ? null : age < 1,
      "Reviewer account age under one day.",
    ),
    reviewerSignal(
      input,
      ids.reviewer[1],
      age == null ? null : age < 7,
      "Reviewer account age under seven days.",
    ),
    reviewerSignal(
      input,
      ids.reviewer[2],
      age == null ? null : age < 30,
      "Reviewer account age under thirty days.",
    ),
    reviewerSignal(
      input,
      ids.reviewer[3],
      age == null ? null : age > 3650,
      "Reviewer account age over ten years.",
    ),
    reviewerSignal(
      input,
      ids.reviewer[4],
      reviewer?.hasPhoto == null ? null : !reviewer.hasPhoto,
      "Profile photo availability as supplied.",
    ),
    reviewerSignal(
      input,
      ids.reviewer[5],
      total == null ? null : total === 1,
      "Supplied total review count equals one.",
    ),
    reviewerSignal(
      input,
      ids.reviewer[6],
      total == null ? null : total < 5,
      "Supplied total review count is under five.",
    ),
    reviewerSignal(
      input,
      ids.reviewer[7],
      total == null ? null : total > 500,
      "Supplied total review count exceeds five hundred.",
    ),
    reviewerSignal(
      input,
      ids.reviewer[8],
      total == null ? null : total > 1000,
      "Supplied total review count exceeds one thousand.",
    ),
    reviewerSignal(
      input,
      ids.reviewer[9],
      oneStarShare === null ? null : oneStarShare > 0.5,
      "More than half of supplied reviewer ratings are one-star.",
    ),
    reviewerSignal(
      input,
      ids.reviewer[10],
      oneStarShare === null ? null : oneStarShare > 0.8,
      "More than eighty percent of supplied reviewer ratings are one-star.",
    ),
    reviewerSignal(
      input,
      ids.reviewer[11],
      oneStarShare === null ? null : oneStarShare < 0.2,
      "Fewer than twenty percent of supplied reviewer ratings are one-star.",
    ),
    reviewerSignal(
      input,
      ids.reviewer[12],
      hour == null ? null : hour >= 5,
      "At least five reviews per hour in supplied metadata.",
    ),
    reviewerSignal(
      input,
      ids.reviewer[13],
      hour == null ? null : hour >= 10,
      "At least ten reviews per hour in supplied metadata.",
    ),
    reviewerSignal(
      input,
      ids.reviewer[14],
      hour == null ? null : hour >= 20,
      "At least twenty reviews per hour in supplied metadata.",
    ),
    reviewerSignal(
      input,
      ids.reviewer[15],
      reviewedBusinesses == null ? null : reviewedBusinesses === 1,
      "Supplied reviewed-business count equals one.",
    ),
    reviewerSignal(
      input,
      ids.reviewer[16],
      reviewedBusinesses == null ? null : reviewedBusinesses > 20,
      "Supplied reviewed-business count exceeds twenty.",
    ),
    reviewerSignal(
      input,
      ids.reviewer[17],
      reviewer ? !name?.trim() : null,
      "Reviewer name availability in supplied metadata.",
    ),
    reviewerSignal(
      input,
      ids.reviewer[18],
      nameLength == null ? null : nameLength < 3,
      "Supplied reviewer display-name length is under three.",
    ),
    reviewerSignal(
      input,
      ids.reviewer[19],
      nameLength == null ? null : nameLength > 60,
      "Supplied reviewer display-name length exceeds sixty.",
    ),
    reviewerSignal(
      input,
      ids.reviewer[20],
      reviewer?.postingTimes == null ? null : reviewer.postingTimes.length === 0,
      "Posting-time history availability.",
    ),
    reviewerSignal(
      input,
      ids.reviewer[21],
      reviewer?.reviewedCompetitorNames == null
        ? null
        : reviewer.reviewedCompetitorNames.length === 0,
      "Competitor history availability.",
    ),
    reviewerSignal(
      input,
      ids.reviewer[22],
      reviewer?.locationCountry == null ? null : false,
      "Reviewer location country was supplied.",
    ),
    reviewerSignal(
      input,
      ids.reviewer[23],
      total == null ? null : false,
      "Reviewer aggregate history count was supplied.",
    ),
    reviewerSignal(
      input,
      ids.reviewer[24],
      reviewer == null ? null : false,
      "Reviewer metadata object was supplied.",
    ),
  ];
  const measuredTemporal: RuleCheck[] = [
    observed(
      ids.temporal[0],
      "temporal",
      validTime ? time!.getUTCMonth() === 0 : null,
      0,
      "Review timestamp falls in January UTC.",
    ),
    observed(
      ids.temporal[1],
      "temporal",
      validTime ? time!.getUTCDate() === 1 : null,
      0,
      "Review timestamp falls on the first day of a month UTC.",
    ),
    observed(
      ids.temporal[2],
      "temporal",
      validTime ? time!.getUTCDate() <= 7 : null,
      0,
      "Review timestamp falls in the first week of a month UTC.",
    ),
    observed(
      ids.temporal[3],
      "temporal",
      validTime ? time!.getUTCDate() >= 24 : null,
      0,
      "Review timestamp falls in the final week of a month UTC.",
    ),
    observed(
      ids.temporal[4],
      "temporal",
      validTime ? time!.getUTCDay() >= 1 && time!.getUTCDay() <= 5 : null,
      0,
      "Review timestamp falls on a weekday UTC.",
    ),
    observed(
      ids.temporal[5],
      "temporal",
      validTime ? time!.getUTCDay() === 0 || time!.getUTCDay() === 6 : null,
      0,
      "Review timestamp falls on a weekend UTC.",
    ),
    observed(
      ids.temporal[6],
      "temporal",
      validTime ? time!.getUTCHours() === 0 : null,
      0,
      "Review timestamp is in the midnight UTC hour; local zone may differ.",
    ),
    observed(
      ids.temporal[7],
      "temporal",
      validTime ? time!.getUTCHours() === 12 : null,
      0,
      "Review timestamp is in the noon UTC hour; local zone may differ.",
    ),
    observed(
      ids.temporal[8],
      "temporal",
      validTime ? time!.getUTCMinutes() === 0 : null,
      0,
      "Review timestamp has a zero UTC minute component.",
    ),
    observed(
      ids.temporal[9],
      "temporal",
      input.timeZone ? false : null,
      0,
      "A business-local time zone was not supplied.",
    ),
  ];

  const unavailable = (group: RuleGroup, catalog: readonly string[], reason: string) =>
    completeChecks(
      group,
      catalog,
      new Map(
        catalog.map((id) => [
          id,
          {
            id,
            group,
            status: "not_assessed" as const,
            points: 0,
            evidence: reason,
          },
        ]),
      ),
    );
  const crossPlatform = unavailable(
    "crossPlatform",
    ids.crossPlatform,
    "Google Places-only input contains no independent platform data; no cross-platform lookup was performed.",
  );
  const network = unavailable(
    "network",
    ids.network,
    "Places API does not provide IP, device, browser, connection, or interaction telemetry.",
  );
  const measuredSemantic = semanticPatterns.map(([id, pattern]) =>
    observed(
      id,
      "semantic",
      wordCount ? pattern.test(text) : null,
      0,
      "Topic keyword observation only; it does not establish policy violation.",
    ),
  );
  const measuredPattern = patternPatterns.map(([id, pattern]) =>
    observed(
      id,
      "pattern",
      wordCount ? pattern.test(text) : null,
      0,
      "Text-pattern observation only; it does not establish coordinated or inauthentic activity.",
    ),
  );
  measuredPattern.push(
    observed(
      ids.pattern[49],
      "pattern",
      wordCount ? wordCount <= 5 : null,
      0,
      `Review length is ${wordCount} words; brevity alone does not establish inauthentic activity.`,
    ),
  );
  const languageChecks = languagePatterns.map(([id, pattern]) =>
    observed(
      id,
      "language",
      wordCount ? pattern.test(text) : null,
      0,
      "Language marker observation only; language, dialect, slang, and accusations are not proof of a policy violation.",
    ),
  );

  const checks = [
    ...measuredText,
    ...measuredReviewer,
    ...measuredTemporal,
    ...crossPlatform,
    ...network,
    ...measuredSemantic,
    ...measuredPattern,
    ...languageChecks,
  ];
  return checks;
}
