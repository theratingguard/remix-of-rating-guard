export function programmaticSeoPaths() {
  const review = [];
  const agency = [];
  for (const country of countries) {
    for (const industry of industries) {
      review.push(`/remove-google-review/${industry.slug}/${country.slug}`);
      agency.push(`/start-${industry.slug}-agency/${country.slug}`);
    }
  }
  return {
    review,
    agency,
    partners: countries.map((country) => `/partners/${country.slug}`),
  };
}
